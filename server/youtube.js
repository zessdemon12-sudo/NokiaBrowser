function getAuthState() {
    try {
        if (fs.existsSync(AUTH_FILE)) {
            const raw = fs.readFileSync(AUTH_FILE, 'utf8');
            const parsed = JSON.parse(raw);
            if (hasValidCookies() && !parsed.loggedIn) {
                parsed.loggedIn = true;
                if (!parsed.username) parsed.username = 'YouTube User (Cookie)';
            }
            return parsed;
        }
    } catch (e) {}
    
    // Check if cookies.txt exists standalone
    if (hasValidCookies()) {
        return {
            loggedIn: true,
            username: 'YouTube User (Cookie)',
            isDemo: false,
            subscriptions: [...DEMO_CHANNELS]
        };
    }

    return {
        loggedIn: false,
        username: 'Guest',
        isDemo: false,
        subscriptions: []
    };
}

function saveAuthState(state) {
    try {
        if (!fs.existsSync(DATA_DIR)) fs.mkdirSync(DATA_DIR, { recursive: true });
        fs.writeFileSync(AUTH_FILE, JSON.stringify(state, null, 2), 'utf8');
    } catch (e) {
        console.error('[YouTube Auth] Error saving auth state:', e.message);
    }
}

function hasValidCookies() {
    try {
        if (fs.existsSync(COOKIES_FILE)) {
            const stats = fs.statSync(COOKIES_FILE);
            return stats.size > 20;
        }
    } catch (e) {}
    return false;
}

function convertCookieToNetscape(rawCookieStr) {
    if (!rawCookieStr || typeof rawCookieStr !== 'string') return '';
    const trimmed = rawCookieStr.trim();
    if (trimmed.includes('\t') && (trimmed.includes('.youtube.com') || trimmed.includes('youtube.com') || trimmed.includes('# Netscape'))) {
        return trimmed;
    }
    const lines = [
        '# Netscape HTTP Cookie File',
        '# https://curl.se/docs/http-cookies.html',
        '# This file was generated by Nokia Gateway YouTube Auth',
        ''
    ];
    const pairs = trimmed.split(';');
    for (const pair of pairs) {
        const eqIdx = pair.indexOf('=');
        if (eqIdx === -1) continue;
        const key = pair.substring(0, eqIdx).trim();
        const val = pair.substring(eqIdx + 1).trim();
        if (!key) continue;
        lines.push(`.youtube.com\tTRUE\t/\tTRUE\t2147483647\t${key}\t${val}`);
    }
    return lines.join('\n');
}

function saveCookiesFromRaw(raw) {
    const netscape = convertCookieToNetscape(raw);
    if (!netscape) return false;
    try {
        if (!fs.existsSync(DATA_DIR)) fs.mkdirSync(DATA_DIR, { recursive: true });
        fs.writeFileSync(COOKIES_FILE, netscape, 'utf8');
        const state = getAuthState();
        state.loggedIn = true;
        state.username = 'YouTube User';
        state.isDemo = false;
        if (!state.subscriptions || state.subscriptions.length === 0) {
            state.subscriptions = [...DEMO_CHANNELS];
        }
        saveAuthState(state);
        feedCache.clear();
        return true;
    } catch (e) {
        console.error('[YouTube Auth] Error saving cookies:', e.message);
        return false;
    }
}

function clearAuth() {
    try {
        if (fs.existsSync(COOKIES_FILE)) fs.unlinkSync(COOKIES_FILE);
    } catch (e) {}
    saveAuthState({
        loggedIn: false,
        username: 'Guest',
        isDemo: false,
        subscriptions: []
    });
    feedCache.clear();
}

function isYouTubeUrl(targetUrl) {
    try {
        const u = new URL(targetUrl);
        const host = u.hostname.toLowerCase();
        return host === 'youtube.com' ||
               host === 'www.youtube.com' ||
               host === 'm.youtube.com' ||
               host === 'youtu.be' ||
               host.endsWith('.youtube.com');
    } catch (e) {
        return false;
    }
}

function extractVideoId(targetUrl) {
    try {
        const u = new URL(targetUrl);
        if (u.hostname === 'youtu.be') {
            const id = u.pathname.substring(1).split(/[?#&]/)[0];
            if (id && id.length === 11 && !id.startsWith('UC')) return id;
        }
        if (u.searchParams.has('v')) {
            const id = u.searchParams.get('v');
            if (id && id.length === 11 && !id.startsWith('UC')) return id;
        }
        const m = u.pathname.match(/\/(?:embed|v|shorts)\/([a-zA-Z0-9_-]{11})(?:[?#&]|$)/);
        if (m) return m[1];
    } catch (e) {}
    const directMatch = targetUrl.match(/[?&]v=([a-zA-Z0-9_-]{11})(?:[&#]|$)/) || targetUrl.match(/youtu\.be\/([a-zA-Z0-9_-]{11})(?:[?#&]|$)/);
    return directMatch ? directMatch[1] : null;
}

function formatDuration(sec) {
    if (!sec || isNaN(sec) || sec <= 0) return '';
    const s = Math.floor(sec);
    const m = Math.floor(s / 60);
    const remS = s % 60;
    const padS = remS < 10 ? '0' + remS : remS;
    if (m < 60) {
        return `${m}:${padS}`;
    }
    const h = Math.floor(m / 60);
    const remM = m % 60;
    const padM = remM < 10 ? '0' + remM : remM;
    return `${h}:${padM}:${padS}`;
}

function formatViews(views) {
    if (!views || isNaN(views)) return '';
    const v = parseInt(views, 10);
    if (v >= 1000000) {
        return (v / 1000000).toFixed(1).replace(/\.0$/, '') + 'M views';
    }
    if (v >= 1000) {
        return (v / 1000).toFixed(1).replace(/\.0$/, '') + 'K views';
    }
    return v + ' views';
}

function runYtDlp(args, timeoutMs = 15000) {
    return new Promise((resolve, reject) => {
        execFile(YT_DLP_PATH, args, { maxBuffer: 10 * 1024 * 1024, timeout: timeoutMs }, (err, stdout, stderr) => {
            if (err) {
                return reject(new Error(stderr || err.message));
            }
            resolve(stdout);
        });
    });
}

async function searchYouTube(query, count = 15) {
    const cleanQ = query.trim();
    const cacheKey = cleanQ.toLowerCase();
    const now = Date.now();

    if (searchCache.has(cacheKey)) {
        const entry = searchCache.get(cacheKey);
        if (now - entry.timestamp < CACHE_TTL_MS) {
            return entry.data;
        }
    }

    try {
        const args = ['--dump-json', `ytsearch${count}:${cleanQ}`, '--flat-playlist', '--no-warnings'];
        if (hasValidCookies()) {
            args.unshift('--cookies', COOKIES_FILE);
        }

        const stdout = await runYtDlp(args, 15000);
        const lines = stdout.trim().split('\n');
        const results = [];
        for (let i = 0; i < lines.length; i++) {
            const line = lines[i].trim();
            if (!line) continue;
            try {
                const item = JSON.parse(line);
                const id = item.id;
                if (!id || id.length !== 11 || id.startsWith('UC') || item._type === 'channel' || item._type === 'playlist') {
                    continue;
                }
                const title = item.title || `Video ${id}`;
                const duration = item.duration_string || formatDuration(item.duration);
                const channel = item.channel || item.uploader || '';
                const views = formatViews(item.view_count);
                let desc = item.description || '';
                if (desc.length > 75) desc = desc.substring(0, 72) + '...';

                let thumb = `https://i.ytimg.com/vi/${id}/hqdefault.jpg`;
                if (item.thumbnails && item.thumbnails.length > 0) {
                    thumb = item.thumbnails[0].url;
                }

                results.push({
                    id,
                    title,
                    duration,
                    channel,
                    views,
                    desc,
                    thumb
                });
            } catch (e) {}
        }

        searchCache.set(cacheKey, { timestamp: now, data: results });
        return results;
    } catch (e) {
        console.error('[YouTube Search Error]:', e.message);
        return [];
    }
}

async function getVideoInfo(videoId) {
    const now = Date.now();
    if (videoInfoCache.has(videoId)) {
        const entry = videoInfoCache.get(videoId);
        if (now - entry.timestamp < CACHE_TTL_MS) {
            return entry.data;
        }
    }

    try {
        const args = ['--dump-json', `https://www.youtube.com/watch?v=${videoId}`, '--no-playlist', '--no-warnings'];
        if (hasValidCookies()) {
            args.unshift('--cookies', COOKIES_FILE);
        }
        const stdout = await runYtDlp(args, 15000);

        const data = JSON.parse(stdout.trim());
        const info = {
            id: videoId,
            title: data.title || `YouTube Video ${videoId}`,
            channel: data.channel || data.uploader || 'YouTube Creator',
            views: formatViews(data.view_count),
            duration: data.duration_string || formatDuration(data.duration),
            uploadDate: data.upload_date ? `${data.upload_date.substring(0,4)}-${data.upload_date.substring(4,6)}-${data.upload_date.substring(6,8)}` : '',
            desc: data.description || '',
            thumb: `https://i.ytimg.com/vi/${videoId}/hqdefault.jpg`
        };

        videoInfoCache.set(videoId, { timestamp: now, data: info });
        return info;
    } catch (e) {
        console.error('[YouTube Video Info Error]:', e.message);
        return {
            id: videoId,
            title: `YouTube Video (${videoId})`,
            channel: 'YouTube',
            views: '',
            duration: '',
            uploadDate: '',
            desc: '',
            thumb: `https://i.ytimg.com/vi/${videoId}/hqdefault.jpg`
        };
    }
}

async function getSubscriptionsFeed(count = 15) {
    const auth = getAuthState();
    if (!auth.loggedIn) return [];

    const now = Date.now();
    if (feedCache.has('feed')) {
        const entry = feedCache.get('feed');
        if (now - entry.timestamp < 3 * 60 * 1000) {
            return entry.data;
        }
    }

    let videos = [];

    // Attempt real live subscriptions feed if Netscape cookies exist and not demo
    if (hasValidCookies() && !auth.isDemo) {
        try {
            console.log('[YouTube Auth] Querying live YouTube subscriptions feed...');
            const stdout = await runYtDlp([
                '--cookies', COOKIES_FILE,
                '--dump-json',
                '--flat-playlist',
                '--playlist-end', String(count),
                '--no-warnings',
                'https://www.youtube.com/feed/subscriptions'
            ], 15000);

            const lines = stdout.trim().split('\n');
            for (const line of lines) {
                if (!line.trim()) continue;
                try {
                    const item = JSON.parse(line);
                    const id = item.id;
                    if (!id) continue;
                    videos.push({
                        id,
                        title: item.title || `Video ${id}`,
                        duration: item.duration_string || formatDuration(item.duration),
                        channel: item.channel || item.uploader || 'Creator',
                        views: formatViews(item.view_count),
                        thumb: (item.thumbnails && item.thumbnails.length > 0) ? item.thumbnails[0].url : `https://i.ytimg.com/vi/${id}/hqdefault.jpg`
                    });
                } catch (e) {}
            }
        } catch (err) {
            console.warn('[YouTube Auth] Subscriptions feed query fallback:', err.message);
        }
    }

    // Fallback or Demo mode: Pull recent videos from subscribed channels
    if (videos.length === 0 && auth.subscriptions && auth.subscriptions.length > 0) {
        const channels = auth.subscriptions.slice(0, 5);
        const fetches = channels.map(c => searchYouTube(`${c.name} video`, 3));
        const resLists = await Promise.all(fetches);
        for (const list of resLists) {
            if (Array.isArray(list)) {
                for (const v of list) {
                    if (v && v.id && v.id.length === 11 && !v.id.startsWith('UC')) {
                        videos.push(v);
                    }
                }
            }
        }
        videos = videos.slice(0, count);
    }

    feedCache.set('feed', { timestamp: now, data: videos });
    return videos;
}

async function handleYouTubeRequest(targetUrl, res, gatewayHost, decodeHtmlEntities) {
    try {
        const u = new URL(targetUrl);
        const pathname = u.pathname;
        const videoId = extractVideoId(targetUrl);
        const searchQuery = u.searchParams.get('search_query') || u.searchParams.get('q') || '';
        const isSearch = pathname === '/results' || pathname === '/search' || (u.searchParams.has('search_query'));

        // 1. Account Login / Sign-in Page
        if (pathname === '/login' || pathname === '/signin') {
            return await handleLoginPage(u, res, gatewayHost);
        }

        // 2. Account Logout
        if (pathname === '/logout' || pathname === '/signout') {
            return await handleLogoutPage(res, gatewayHost);
        }

        // 3. Subscriptions Feed (/feed/subscriptions)
        if (pathname === '/feed/subscriptions' || pathname === '/subscriptions') {
            return await handleSubscriptionsPage(res, gatewayHost);
        }

        // 4. Subscribed Channels List (/feed/channels)
        if (pathname === '/feed/channels' || pathname === '/channels') {
            return await handleChannelsPage(res, gatewayHost);
        }

        // 5. In-App Subscribe action
        if (pathname === '/subscribe') {
            const chName = u.searchParams.get('name') || 'Channel';
            const chId = u.searchParams.get('id') || ('ch_' + Date.now());
            const auth = getAuthState();
            if (!auth.subscriptions) auth.subscriptions = [];
            if (!auth.subscriptions.some(c => c.name.toLowerCase() === chName.toLowerCase())) {
                auth.subscriptions.unshift({ id: chId, name: chName });
                saveAuthState(auth);
                feedCache.clear();
            }
            const lines = [
                'META:TITLE=Subscribed to ' + chName,
                'META:URL=https://www.youtube.com/subscribe',
                'META:HTTPS=1',
                'H1:Subscribed!',
                'P:You are now subscribed to ' + chName + '.',
                'L:https://www.youtube.com/feed/subscriptions\t📺 View Subscriptions Feed',
                'L:https://www.youtube.com/feed/channels\t📑 Subscribed Channels (' + auth.subscriptions.length + ')',
                'HR:',
                'L:https://www.youtube.com\t📺 YouTube Home'
            ];
            res.writeHead(200, { 'Content-Type': 'text/plain; charset=utf-8' });
            return res.end(lines.join('\n'));
        }

        // 6. In-App Unsubscribe action
        if (pathname === '/unsubscribe') {
            const chName = u.searchParams.get('name') || '';
            const auth = getAuthState();
            if (auth.subscriptions) {
                auth.subscriptions = auth.subscriptions.filter(c => c.name.toLowerCase() !== chName.toLowerCase());
                saveAuthState(auth);
                feedCache.clear();
            }
            const lines = [
                'META:TITLE=Unsubscribed',
                'META:URL=https://www.youtube.com/unsubscribe',
                'META:HTTPS=1',
                'H1:Unsubscribed',
                'P:Removed ' + chName + ' from your subscriptions.',
                'L:https://www.youtube.com/feed/channels\t📑 Subscribed Channels (' + (auth.subscriptions ? auth.subscriptions.length : 0) + ')',
                'L:https://www.youtube.com/feed/subscriptions\t📺 View Subscriptions Feed',
                'HR:',
                'L:https://www.youtube.com\t📺 YouTube Home'
            ];
            res.writeHead(200, { 'Content-Type': 'text/plain; charset=utf-8' });
            return res.end(lines.join('\n'));
        }

        // 7. Watch Page
        if (videoId && (pathname === '/watch' || u.hostname === 'youtu.be' || pathname.startsWith('/shorts/') || pathname.startsWith('/embed/'))) {
            return await handleWatchPage(videoId, targetUrl, res, gatewayHost, decodeHtmlEntities);
        }

        // 8. Search Results Page
        if (isSearch) {
            return await handleSearchPage(searchQuery, targetUrl, res, gatewayHost);
        }

        // 9. YouTube Mobile Homepage
        return await handleHomePage(targetUrl, res, gatewayHost);

    } catch (e) {
        console.error('[YouTube Request Error]:', e.message);
        res.writeHead(200, { 'Content-Type': 'text/plain; charset=utf-8' });
        res.end(`META:TITLE=YouTube Error\nH1:YouTube Error\nP:${e.message}\nHR:\nL:search:youtube\t🔍 Search YouTube\nL:https://www.youtube.com\t📺 YouTube Home`);
    }
}

