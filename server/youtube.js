    lines.push('META:URL=https://www.youtube.com/feed/subscriptions');
    lines.push('META:HTTPS=1');
    lines.push('H1:My Subscriptions');

    if (!auth.loggedIn) {
        lines.push('P:Sign in to view videos from your subscribed channels.');
        lines.push('L:https://www.youtube.com/login\t🔑 Sign In to YouTube');
        lines.push('L:https://www.youtube.com/login?demo=1\t⚡ Instant Sign In (Demo Account)');
        lines.push('HR:');
        lines.push('L:https://www.youtube.com\t📺 YouTube Home');
        res.writeHead(200, { 'Content-Type': 'text/plain; charset=utf-8' });
        return res.end(lines.join('\n'));
    }

